def publish(files, *, check=False, out=OUT):
    if any(
        not name.endswith(".md") or Path(name).is_absolute() or ".." in Path(name).parts
        for name in files
    ):
        raise ValueError("Only owned Markdown outputs are allowed")
    for path in [out, *out.rglob("*"), *(out / name for name in files)]:
        if path.is_symlink() or any(p.is_symlink() for p in path.parents):
            raise ValueError("Symlink output refused: " + str(path))
        if path.exists() and not path.is_file() and not path.is_dir():
            raise ValueError("Unsafe output: " + str(path))
    existing = {str(p.relative_to(out)) for p in out.rglob("*") if p.is_file()}
    obsolete = existing - files.keys()
    for name in obsolete:
        if BANNER.strip() not in (out / name).read_text():
            raise ValueError("Unowned output must not be removed: " + name)
    stale = [
        name
        for name, data in files.items()
        if not (out / name).is_file() or (out / name).read_text() != data
    ]
    if check and (stale or obsolete):
        raise ValueError("Generated Markdown drift: " + ", ".join(sorted(set(stale) | obsolete)))
    if not check:
        for name in stale:
            p = out / name
            p.parent.mkdir(parents=True, exist_ok=True)
            temp = p.with_suffix(".tmp")
            if temp.exists() or temp.is_symlink():
                raise ValueError("Unowned temporary output: " + str(temp))
            temp.write_text(files[name])
            temp.replace(p)
        for name in obsolete:
            (out / name).unlink()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = render()
    publish(files, check=args.check)
    print(f"Generated Markdown {'verified' if args.check else 'updated'}: {len(files)} files")


if __name__ == "__main__":
    main()
