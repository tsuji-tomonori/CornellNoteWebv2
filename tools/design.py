def cell(value) -> str:
    def raw(item):
        if isinstance(item, dict):
            return "; ".join(f"{k}: {raw(v)}" for k, v in sorted(item.items()))
        if isinstance(item, list):
            return ", ".join(raw(v) for v in item)
        return str(item)

    return (
        raw(value)
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace("|", "\\|")
        .replace("\n", "<br>")
    )


def suppression_reason(value):
    try:
        return base64.b64decode(value, validate=True).decode("utf-8")
    except (binascii.Error, UnicodeDecodeError):
        return value


def table(headers, rows) -> str:
    rows = list(rows)
    if not rows:
        return "該当なし。\n\n"
    return (
        "| "
        + " | ".join(headers)
        + " |\n| "
        + " | ".join("---" for _ in headers)
        + " |\n"
        + "".join("| " + " | ".join(cell(v) for v in row) + " |\n" for row in rows)
        + "\n"
    )


def source(path, line=None) -> str:
    name = str(path.relative_to(ROOT)) if isinstance(path, Path) else path
    return f"[{name}{':' + str(line) if line else ''}]({SOURCE_URL}{name}{'#L' + str(line) if line else ''})"


def page(title, body) -> str:
    return f"# {title}\n\n{BANNER}{body.rstrip()}\n"


def fields(schema, schemas, prefix="$", required=True, seen=()) -> list:
    if "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        if name in seen:
            return [(prefix, name, required, "再帰参照", "")]
        return fields(schemas[name], schemas, prefix, required, (*seen, name))
    kind = schema.get("type", "union" if "anyOf" in schema else "object")
    constraints = {
        k: v
        for k, v in schema.items()
        if k not in {"properties", "items", "anyOf", "required", "type", "title", "description"}
    }
    rows = [
        (prefix, kind, "必須" if required else "省略可", schema.get("description", ""), constraints)
    ]
    for name, value in schema.get("properties", {}).items():
        rows += fields(
            value, schemas, prefix + "." + name, name in schema.get("required", []), seen
        )
    if "items" in schema:
        rows += fields(schema["items"], schemas, prefix + "[]", False, seen)
    for i, value in enumerate(schema.get("anyOf", []), 1):
        rows += fields(value, schemas, f"{prefix} (候補{i})", required, seen)
    return rows


def function_at(path, name):
    tree = ast.parse(path.read_text())
    return next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == name)


def errors(node, path):
    result = []
    for n in ast.walk(node):
        if isinstance(n, ast.Call) and ast.unparse(n.func) == "HTTPException":
            values = dict(zip(["status_code", "detail"], n.args, strict=False))
            values.update({k.arg: k.value for k in n.keywords})
            result.append(
                (
                    ast.literal_eval(values["status_code"]),
                    ast.literal_eval(values["detail"]),
                    source(path, n.lineno),
                )
            )
    return sorted(result)


def database_docs(queries):
    statements = []
    for path in sorted((ROOT / "backend/migrations").glob("*.sql")):
        statements += [(path, n) for n in sqlglot.parse(path.read_text(), dialect="postgres") if n]
    path = ROOT / "backend/src/app/migrate.py"
    for node in ast.walk(ast.parse(path.read_text())):
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "execute"
            and node.args
        ):
            literal = node.args[0]
            if (
                isinstance(literal, ast.Constant)
                and isinstance(literal.value, str)
                and literal.value.startswith(("CREATE TABLE", "COMMENT ON"))
            ):
                statements += [(path, sqlglot.parse_one(literal.value, dialect="postgres"))]
    comments = {}
    tables = {}
    indexes = []
    for path, statement in statements:
        if isinstance(statement, exp.Comment):
            comments[statement.this.sql(dialect="postgres")] = statement.expression.this
        elif isinstance(statement, exp.Create) and statement.kind == "TABLE":
            tables[statement.this.this.name] = (path, statement)
        elif isinstance(statement, exp.Create) and statement.kind == "INDEX":
            indexes.append((path, statement))
        else:
            raise ValueError("Unsupported DDL; extend extractor: " + statement.sql())
    files = {}
    er = ["erDiagram"]
    for name, (path, statement) in sorted(tables.items()):
        if name not in comments:
            raise ValueError("Missing Japanese table comment: " + name)
        columns = []
        er.append(f"    {name} {{")
        for c in statement.this.expressions:
            if not isinstance(c, exp.ColumnDef):
                raise ValueError("Unsupported table constraint: " + c.sql())
            description = comments.get(name + "." + c.name)
            if not description:
                raise ValueError("Missing column comment: " + name + "." + c.name)
            kinds = [constraint.kind for constraint in c.constraints]
            if any(isinstance(k, exp.Reference) for k in kinds):
                raise ValueError("Foreign key requires ER extraction support")
            pk = any(isinstance(k, exp.PrimaryKeyColumnConstraint) for k in kinds)
            nonnull = pk or any(isinstance(k, exp.NotNullColumnConstraint) for k in kinds)
            columns.append(
                (
                    c.name,
                    c.kind.sql(dialect="postgres"),
                    "不可" if nonnull else "可",
                    "PK" if pk else "",
                    ", ".join(k.sql(dialect="postgres") for k in kinds),
                    description,
                )
            )
            er.append(
                f'        {c.kind.sql(dialect="postgres").replace("(", "_").replace(")", "")} {c.name}{" PK" if pk else ""} "{description}"'
            )
        er.append("    }")
        relevant = [q for q in queries if q["table"] == name]
        body = (
            comments[name]
            + "\n\n正本: "
            + source(path)
            + "\n\n## カラム\n\n"
            + table(["カラム", "型", "NULL", "キー", "制約・既定値", "日本語説明"], columns)
        )
        body += "## インデックス\n\n" + table(
            ["名前", "定義", "正本"],
            (
                (n.this.name, n.sql(dialect="postgres"), source(p))
                for p, n in indexes
                if n.this.args["table"].name == name
            ),
        )
        body += "## API・SQLによる操作\n\n" + table(
            ["API", "CRUD", "SQL"],
            ((q["api"], q["operation"], source(q["source"])) for q in relevant),
        )
        body += "## DDL\n\n```sql\n" + statement.sql(dialect="postgres", pretty=True) + ";\n```\n"
        files[f"database/tables/{name}.gen.md"] = page(name + " テーブル仕様", body)
    files["database/er.gen.md"] = page(
        "DB全体ER図",
        "DDLに定義された物理テーブルを表示する。現在、外部キーは定義されていないため関連線はない。owner_idは外部認証主体でありDB外部キーではない。\n\n```mermaid\n"
        + "\n".join(er)
        + "\n```",
    )
    operations = {"INSERT": "C", "SELECT": "R", "UPDATE": "U", "DELETE": "D"}
    names = sorted(tables)
    apis = sorted({q["api"] for q in queries})
    matrix = [
        (
            api,
            *[
                " / ".join(
                    sorted(
                        {
                            operations[q["operation"]]
                            for q in queries
                            if q["api"] == api and q["table"] == name
                        }
                    )
                )
                or "—"
                for name in names
            ],
        )
        for api in apis
    ]
    diagrams = ""
    for name in names:
        for operation, code in operations.items():
            relevant = sorted(
                {q["api"] for q in queries if q["table"] == name and q["operation"] == operation}
            )
            if relevant:
                diagram = 'flowchart TD\n  DB["' + name + '"]'
                for i, api in enumerate(relevant):
                    diagram += f'\n  A{i}["{api}"] -->|{code}| DB'
                diagrams += f"## {name} {operation}\n\n```mermaid\n{diagram}\n```\n\n"
    files["database/crud.gen.md"] = page(
        "テーブル × API CRUD図",
        "C=作成 / R=参照 / U=更新 / D=削除。SQL文種別に基づく対応で、UPDATE・DELETEのWHERE判定は別のRとして加算しない。schema_migrationsはAPIから直接操作せずmigrationで管理する。\n\n"
        + table(["API", *names], matrix)
        + diagrams
        + "## SQL・カラム詳細\n\n"
        + table(
            ["テーブル", "API", "SQL操作", "参照列", "書込列", "正本"], (crud(q) for q in queries)
        ),
    )
    files["database/migrations.gen.md"] = page(
        "マイグレーション仕様",
        "適用処理: "
        + source("backend/src/app/migrate.py")
        + "\n\n"
        + table(
            ["ファイル", "SHA-256", "DDL"],
            (
                (source(p), hashlib.sha256(p.read_bytes()).hexdigest(), p.read_text())
                for p in sorted((ROOT / "backend/migrations").glob("*.sql"))
            ),
        ),
    )
    files["database/index.gen.md"] = page(
        "DB一覧",
        table(
            ["テーブル", "仕様", "説明"],
            ((n, f"[仕様](tables/{n}.gen.md)", comments[n]) for n in sorted(tables)),
        )
        + "\n[ER図](er.gen.md) · [CRUD](crud.gen.md) · [マイグレーション](migrations.gen.md)\n",
    )
    return files


def crud(q):
    n = sqlglot.parse_one((ROOT / q["source"]).read_text(), dialect="postgres")
    read = sorted({c.name for c in n.find_all(exp.Column)})
    write = []
    if isinstance(n, exp.Insert):
        write = [c.name for c in n.this.expressions]
    if isinstance(n, exp.Update):
        write = [c.this.name for c in n.expressions]
    return q["table"], q["api"], q["operation"], read, write, source(q["source"])


def api_docs(queries, catalog):
    verify_framework(app)
    spec = app.openapi()
    schemas = spec.get("components", {}).get("schemas", {})
    routes = [r for r in iter_route_contexts(app.routes) if isinstance(r.original_route, APIRoute)]
    definitions = [
        (p, m.upper(), d)
        for p, methods in sorted(spec["paths"].items())
        for m, d in sorted(methods.items())
        if m in {"get", "put", "post", "delete", "patch", "head", "options"}
    ]
    if len(definitions) != len(routes) or len({d["operationId"] for _, _, d in definitions}) != len(
        definitions
    ):
        raise ValueError("OpenAPI/route cardinality or operation ID conflict")
    files, overview = {}, []
    for path, method, d in definitions:
        matching = [
            r
            for r in routes
            if r.operation_id == d["operationId"] and r.path == path and method in r.methods
        ]
        if len(matching) != 1:
            raise ValueError("OpenAPI and effective route must be one-to-one")
        route = matching[0]
        if not isinstance(route.original_route, ObservedRoute):
            raise ValueError("Log catalog requires ObservedRoute: " + d["operationId"])
        op = d["operationId"]
        handler_path = Path(inspect.getfile(route.endpoint))
        handler = function_at(handler_path, route.endpoint.__name__)
        function_path = handler_path.parent / "functions.py"
        if function_path.exists():
            function = function_at(function_path, "execute")
        elif op == "local_login":
            function_path = ROOT / "backend/src/app/auth.py"
            function = function_at(function_path, "local_login")
        else:
            function_path, function = handler_path, handler
        authenticated = bool(d.get("security"))
        reqs = [
            r
            for r in catalog["requirements"]
            if str(function_path.relative_to(ROOT)) in r["traces"]["implementation"]
            or str(handler_path.relative_to(ROOT)) in r["traces"]["implementation"]
        ]
        qs = [q for q in queries if q["api"] == handler_path.parent.name]
        err = errors(function, function_path)
        auth_err = []
        if authenticated:
            auth_path = ROOT / "backend/src/app/auth.py"
            auth_err = errors(function_at(auth_path, "authenticate"), auth_path)
            err += auth_err
        base = f"apis/{op}/"
        intro = f"`{method} {path}` / operationId: `{op}`\n\nハンドラ: {source(handler_path, handler.lineno)}\n\n処理: {source(function_path, function.lineno)}\n\n"
        overview.append(
            (
                op,
                method,
                path,
                "Bearer JWT" if authenticated else "なし（local_loginはlocalモードのみ）",
                f"[{op}]({op}/if.gen.md)",
            )
        )
        params = d.get("parameters", [])
        expected_path = set(re.findall(r"\{([^}]+)\}", path))
        if expected_path != {p["name"] for p in params if p["in"] == "path" and p.get("required")}:
            raise ValueError("Path parameter mismatch: " + op)
        body = (
            intro
            + "## 認証\n\n"
            + (
                "Bearer JWT。Depends(authenticate)でCognitoまたはローカルJWTを検証する。\n\n"
                if authenticated
                else "OpenAPI上の認証依存なし。実装中のモード制限・入力判定はmessagesを参照。\n\n"
            )
        )
        for location, title in [
            ("header", "Headers"),
            ("path", "Path Parameters"),
            ("query", "Query Parameters"),
        ]:
            selected_params = [p for p in params if p["in"] == location]
            rows = [
                (
                    p["name"],
                    schema_name(p["schema"]),
                    p.get("required", False),
                    p.get("description", ""),
                    p["schema"],
                )
                for p in selected_params
            ]
            if location == "header" and authenticated:
                rows.append(
                    (
                        "Authorization",
                        "Bearer JWT",
                        True,
                        "本人のCognitoまたはローカルJWT",
                        "署名・有効期限・subを検証する",
                    )
                )
            body += f"## {title}\n\n" + table(["項目", "型", "必須", "説明", "制約"], rows)
        for media, content in d.get("requestBody", {}).get("content", {}).items():
            body += (
                "## Data / Request "
                + media
                + "\n\n"
                + table(["項目", "型", "必須", "説明", "制約"], fields(content["schema"], schemas))
            )
        for status, response in sorted(d["responses"].items()):
            body += f"## Response {status}\n\n{response['description']}\n\n"
            for media, content in response.get("content", {}).items():
                body += (
                    media
                    + "\n\n"
                    + table(
                        ["項目", "型", "必須", "説明", "制約"],
                        fields(content.get("schema", {}), schemas),
                    )
                )
        body += "## 実装から抽出した追加エラー\n\n" + table(
            ["HTTP", "detail（文字列）", "発生箇所"], sorted(set(err))
        )
        files[base + "if.gen.md"] = page(op + " IF仕様", body)
        response_table = table(["HTTP", "処理区分", "条件", "応答内容"], response_cases(d, err))
        common_table = table(
            ["HTTP", "処理区分", "条件", "応答内容"], routing_cases(app.router.redirect_slashes)
        )
        incoming = [
            (p["in"], p["name"], schema_name(p["schema"]), p.get("required", False)) for p in params
        ]
        if authenticated:
            incoming.append(("header", "Authorization", "Bearer JWT", True))
        incoming += [
            ("body", media, schema_name(c["schema"]), d["requestBody"].get("required", False))
            for media, c in d.get("requestBody", {}).get("content", {}).items()
        ]
        access = []
        for q in qs:
            sql = sqlglot.parse_one((ROOT / q["source"]).read_text(), dialect="postgres")
            where = sql.args.get("where")
            access.append(
                (
                    q["table"],
                    q["operation"],
                    q["summary"],
                    where.sql(dialect="postgres") if where else "なし",
                    list(q["params"]),
                )
            )
        files[base + "sequence.gen.md"] = page(
            op + " シーケンス",
            intro
            + "## 入力\n\n"
            + table(["位置", "名前", "型", "必須"], incoming)
            + "## 呼出し・分岐・応答\n\n"
            + "生成ラッパー・with・変換用関数の表示を省き、ifとtry/catch、DB操作、HTTP応答を表示する。breakはその経路の終了。入力と認証に複数の不備がある場合の検証順序は省略し、確定した応答別に分岐する。\n\n"
            + sequence(function, qs, request=f"{method} {path}", definition=d, auth_errors=auth_err)
            + "\n## DBアクセス\n\n"
            + table(["テーブル", "操作", "処理", "絞込み条件", "バインド引数"], access)
            + (
                "接続は`DSQL_HOST`（AWSのAurora DSQL）または`DATABASE_URL`（ローカルPostgreSQL）。接続処理: "
                + source("backend/src/app/db.py")
                + " / ローカル構成: "
                + source("compose.yaml")
                + "\n\n"
                if qs
                else "このAPIはDBへアクセスしない。\n\n"
            )
            + "## このAPIのHTTP応答\n\n"
            + response_table
            + "## ハンドラ到達前の共通応答\n\n"
            + common_table
            + "共通404はURL不一致であり、一覧が空であることを意味しない。500は未処理例外の標準応答であり、DB失敗が必ず500とは限らない（更新競合の409などは個別catchを優先する）。\n\n"
            + "根拠: 実装AST・OpenAPI・現在の標準例外ハンドラ。共通応答の実測テスト: "
            + source("backend/tests/test_response_contract.py")
            + "。CloudFront/API Gateway自身のエラーはこのFastAPI図の対象外。\n",
        )
        body += "## 共通処理を含む応答一覧\n\n" + response_table + common_table
        files[base + "if.gen.md"] = page(op + " IF仕様", body)
        detail = intro + detail_design(
            root=ROOT,
            function=function,
            definition=d,
            queries=qs,
            incoming=incoming,
            responses=response_cases(d, err),
            fields=fields,
            schemas=schemas,
            table=table,
        )
        detail += "## 5. 要件との直接対応\n\n" + table(
            ["要件", "タイトル"], ((r["id"], r["title"]) for r in reqs)
        )
        files[base + "detail-design.gen.md"] = page(op + " 詳細設計", detail)
        files[base + "messages.gen.md"] = page(
            op + " ログ・メッセージ台帳",
            intro + message_design(op, response_cases(d, err), table, source),
        )
        files[base + "query.gen.md"] = page(
            op + " SQL仕様", intro + query_design(ROOT, qs, table, source)
        )
        factors = intro + unit_factors(function, response_cases(d, err), table)
        factors += "## 入力スキーマの制約\n\n" + table(
            ["場所", "スキーマ"],
            [("parameters", params), ("requestBody", d.get("requestBody", {}))],
        )
        factors += "## 要件の受入基準\n\n" + table(
            ["要件", "Given", "When", "Then", "検証ソース（ファイル単位）"],
            (
                (
                    r["id"],
                    ac["given"],
                    ac["when"],
                    ac["then"],
                    [source(t) for t in r["traces"]["tests"]],
                )
                for r in reqs
                for ac in r["acceptance_criteria"]
            ),
        )
        files[base + "unit-test.gen.md"] = page(op + " テスト観点", factors)
    files["apis/index.gen.md"] = page(
        "API一覧",
        table(["Operation", "Method", "Path", "認証", "IF仕様"], overview)
        + "各APIにIF・詳細設計・シーケンス・メッセージ・SQL・テスト観点の6文書を生成する。\n",
    )
